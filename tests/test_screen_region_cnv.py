def test_cram_without_region_reads_keeps_the_run_alive(cohort_dir, run_cli, tmp_path):
    """Regression: a CRAM index records no read counters, so the no-signal path used to
    return library_reads=None; main() then aborted with "TypeError: int() argument must
    be a string, a bytes-like object or a real number, not 'NoneType'" while storing it
    in its int64 array."""
    ref = cohort_dir / "ref.fa"
    victim = make_pten_cnv_fixtures.NORMAL_SAMPLES[-1]
    entries = to_cram_cohort(cohort_dir, tmp_path, all_sample_ids())

    # the same sample, but without a single record on the target chromosome
    stripped = tmp_path / f"{victim}_nochr10.cram"
    with pysam.AlignmentFile(str(cohort_dir / f"{victim}.bam"), "rb") as src:
        with pysam.AlignmentFile(str(stripped), "wc", header=src.header,
                                 reference_filename=str(ref)) as dst:
            for rec in src:
                if rec.reference_name != "chr10":
                    dst.write(rec)
    pysam.index(str(stripped))
    entries = [(sid, stripped if sid == victim else path) for sid, path in entries]
    bam_list = write_bam_list(tmp_path / "no_chr10.txt", entries)

    prefix = tmp_path / "no_chr10"
    run_cli(prefix, bam_list=str(bam_list))     # must complete instead of raising

    rows = read_tsv(Path(f"{prefix}.all_samples.tsv"))
    assert rows[victim]["status"].startswith("NoSignal")
    assert rows[victim]["library_reads"] == "0"
    assert rows[victim]["cnv_call"] == "FAILED_QC"
    assert sum(1 for row in rows.values() if row["status"] == "OK") == len(entries) - 1
    assert rows[make_pten_cnv_fixtures.DEL_SAMPLE]["cnv_call"] == "DEL"


