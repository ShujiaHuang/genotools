def read_tsv(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return {row["sample_id"]: row for row in csv.DictReader(fh, delimiter="\t")}


def write_bam_list(path: Path, entries) -> Path:
    with path.open("w", encoding="utf-8") as fh:
        for sid, bam_path in entries:
            fh.write(f"{sid}\t{bam_path}\n")
    return path


def to_cram(bam: Path, cram: Path, ref: Path) -> None:
    with pysam.AlignmentFile(str(bam), "rb") as src:
        header = src.header
        with pysam.AlignmentFile(str(cram), "wc", header=header, reference_filename=str(ref)) as dst:
            for rec in src:
                dst.write(rec)
    pysam.index(str(cram))


def to_cram_cohort(cohort_dir: Path, outdir: Path, sample_ids) -> list:
    """Convert the fixture BAMs to CRAM and return (sample_id, path) entries."""
    ref = cohort_dir / "ref.fa"
    entries = []
    for sid in sample_ids:
        cram = outdir / f"{sid}.cram"
        to_cram(cohort_dir / f"{sid}.bam", cram, ref)
        entries.append((sid, cram))
    return entries


def all_sample_ids() -> tuple:
    return (*make_pten_cnv_fixtures.NORMAL_SAMPLES,
            make_pten_cnv_fixtures.DEL_SAMPLE, make_pten_cnv_fixtures.DUP_SAMPLE)


def test_bam_cohort_calls_known_cnv_and_reports_no_false_positive(cohort_dir, run_cli, tmp_path):
    prefix = tmp_path / "bam"
    run_cli(prefix)

    rows = read_tsv(Path(f"{prefix}.all_samples.tsv"))
    assert len(rows) == len(make_pten_cnv_fixtures.NORMAL_SAMPLES) + 2
    assert {row["status"] for row in rows.values()} == {"OK"}
    assert {row["library_norm_source"] for row in rows.values()} == {"index"}

    for sid in make_pten_cnv_fixtures.NORMAL_SAMPLES:
        assert rows[sid]["cnv_call"] == "NORMAL", rows[sid]
        assert abs(float(rows[sid]["target_mean_copy_ratio"]) - 1.0) < 0.1

    assert rows[make_pten_cnv_fixtures.DEL_SAMPLE]["cnv_call"] == "DEL"
    assert float(rows[make_pten_cnv_fixtures.DEL_SAMPLE]["target_mean_copy_ratio"]) < 0.8
    assert rows[make_pten_cnv_fixtures.DUP_SAMPLE]["cnv_call"] == "DUP"
    assert float(rows[make_pten_cnv_fixtures.DUP_SAMPLE]["target_mean_copy_ratio"]) > 1.2

    # the estimated span must cover the simulated 20 kb event
    for sid in (make_pten_cnv_fixtures.DEL_SAMPLE, make_pten_cnv_fixtures.DUP_SAMPLE):
        start, end = int(rows[sid]["est_cnv_start"]), int(rows[sid]["est_cnv_end"])
        assert start < make_pten_cnv_fixtures.CNV_START + 5_000
        assert end > make_pten_cnv_fixtures.CNV_END - 5_000

    candidates = read_tsv(Path(f"{prefix}.candidates.tsv"))
    assert set(candidates) == {make_pten_cnv_fixtures.DEL_SAMPLE, make_pten_cnv_fixtures.DUP_SAMPLE}


def test_cram_cohort_falls_back_to_region_library_size(cohort_dir, run_cli, tmp_path):
    """Regression: CRAM/.crai indexes store no read counters, which used to make
    every sample fail with 'Too few valid samples (0)'."""
    ref = cohort_dir / "ref.fa"
    entries = to_cram_cohort(cohort_dir, tmp_path, all_sample_ids())
    bam_list = write_bam_list(tmp_path / "cram_list.txt", entries)

    # precondition: the .crai index really carries no per-contig statistics
    with pysam.AlignmentFile(str(entries[0][1]), reference_filename=str(ref)) as cram:
        assert cram.is_cram
        assert all(stat.mapped == 0 for stat in cram.get_index_statistics())

    prefix = tmp_path / "cram"
    run_cli(prefix, bam_list=str(bam_list))
    rows = read_tsv(Path(f"{prefix}.all_samples.tsv"))

    assert {row["status"] for row in rows.values()} == {"OK"}
    assert {row["library_norm_source"] for row in rows.values()} == {"region"}
    assert rows[make_pten_cnv_fixtures.DEL_SAMPLE]["cnv_call"] == "DEL"
    assert rows[make_pten_cnv_fixtures.DUP_SAMPLE]["cnv_call"] == "DUP"
    for sid in make_pten_cnv_fixtures.NORMAL_SAMPLES:
        assert rows[sid]["cnv_call"] == "NORMAL"


def test_cram_and_bam_agree_on_copy_ratio(cohort_dir, run_cli, tmp_path):
    ref = cohort_dir / "ref.fa"
    cram = tmp_path / f"{make_pten_cnv_fixtures.DEL_SAMPLE}.cram"
    to_cram(cohort_dir / f"{make_pten_cnv_fixtures.DEL_SAMPLE}.bam", cram, ref)

    entries = [(sid, cohort_dir / f"{sid}.bam") for sid in make_pten_cnv_fixtures.NORMAL_SAMPLES]
    entries.append((make_pten_cnv_fixtures.DEL_SAMPLE, cram))
    cram_list = write_bam_list(tmp_path / "mixed.txt", entries)

    bam_prefix, cram_prefix = tmp_path / "mix_bam", tmp_path / "mix_cram"
    run_cli(bam_prefix, bam_list="bam_list.txt")
    run_cli(cram_prefix, bam_list=str(cram_list))

    sid = make_pten_cnv_fixtures.DEL_SAMPLE
    bam_rows = read_tsv(Path(f"{bam_prefix}.all_samples.tsv"))
    cram_rows = read_tsv(Path(f"{cram_prefix}.all_samples.tsv"))
    assert bam_rows[sid]["cnv_call"] == cram_rows[sid]["cnv_call"] == "DEL"
    assert abs(float(bam_rows[sid]["target_mean_copy_ratio"]) - float(cram_rows[sid]["target_mean_copy_ratio"])) < 0.05


def test_full_cohort_bam_and_cram_agree(cohort_dir, run_cli, tmp_path):
    """The same cohort run entirely as BAM and entirely as CRAM must produce
    identical calls and near-identical copy ratios for every sample.

    The two runs deliberately use different library-size sources ('index' vs
    'region'), so this pins down that the choice of anchor does not leak into the
    normalized copy ratio.
    """
    sample_ids = all_sample_ids()
    entries = to_cram_cohort(cohort_dir, tmp_path, sample_ids)
    cram_list = write_bam_list(tmp_path / "cram_list.txt", entries)

    bam_prefix, cram_prefix = tmp_path / "cohort_bam", tmp_path / "cohort_cram"
    run_cli(bam_prefix, bam_list="bam_list.txt")
    run_cli(cram_prefix, bam_list=str(cram_list))

    bam_rows = read_tsv(Path(f"{bam_prefix}.all_samples.tsv"))
    cram_rows = read_tsv(Path(f"{cram_prefix}.all_samples.tsv"))

    assert set(bam_rows) == set(cram_rows) == set(sample_ids)
    assert {row["library_norm_source"] for row in bam_rows.values()} == {"index"}
    assert {row["library_norm_source"] for row in cram_rows.values()} == {"region"}

    for sid in sample_ids:
        assert bam_rows[sid]["status"] == cram_rows[sid]["status"] == "OK", (sid, bam_rows[sid], cram_rows[sid])
        assert bam_rows[sid]["cnv_call"] == cram_rows[sid]["cnv_call"], (sid, bam_rows[sid], cram_rows[sid])
        delta = abs(float(bam_rows[sid]["target_mean_copy_ratio"])
                    - float(cram_rows[sid]["target_mean_copy_ratio"]))
        assert delta < 0.05, (sid, delta, bam_rows[sid], cram_rows[sid])

    # the simulated events are still called, i.e. agreement is not vacuous
    assert bam_rows[make_pten_cnv_fixtures.DEL_SAMPLE]["cnv_call"] == "DEL"
    assert bam_rows[make_pten_cnv_fixtures.DUP_SAMPLE]["cnv_call"] == "DUP"
    assert cram_rows[make_pten_cnv_fixtures.DEL_SAMPLE]["cnv_call"] == "DEL"
    assert cram_rows[make_pten_cnv_fixtures.DUP_SAMPLE]["cnv_call"] == "DUP"


